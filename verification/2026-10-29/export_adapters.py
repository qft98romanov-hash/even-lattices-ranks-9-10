#!/usr/bin/env python3
"""Export the common JSON matrices as Magma/Julia literals, without mathematics.

Run this after export_inputs.py.  The expected answers are assertion targets;
they are never passed to a CAS as precomputed lattice minima or invariants.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
NAMES = ("K9", "K10", "K10_alt", "G8", "E8")


def render() -> dict[str, str]:
    raw = (ROOT / "data/lattices.json").read_bytes()
    obj = json.loads(raw)
    if obj.get("schema") != 1:
        raise ValueError("Unsupported input schema")
    digest = hashlib.sha256(raw).hexdigest()
    magma = ["// Generated by export_adapters.py; do not edit by hand.",
             f'InputSHA256 := "{digest}";', "Matrices := AssociativeArray();",
             "ExpectedDet := AssociativeArray();", "ExpectedMin := AssociativeArray();",
             "ExpectedShells := AssociativeArray();", "ExpectedSmith := AssociativeArray();"]
    julia = ["# Generated by export_adapters.py; do not edit by hand.",
             f'const INPUT_SHA256 = "{digest}"',
             "const MATRICES = Dict{String,Any}()",
             "const EXPECTED_DET = Dict{String,Int}()",
             "const EXPECTED_MIN = Dict{String,Int}()",
             "const EXPECTED_SHELLS = Dict{String,Dict{Int,Int}}()",
             "const EXPECTED_SMITH = Dict{String,Vector{Int}}()"]
    for name in NAMES:
        rows = obj["matrices"][name]
        n = len(rows)
        if not all(len(row) == n and all(type(a) is int for a in row) for row in rows):
            raise ValueError(f"{name}: expected a square integer matrix")
        flat = ", ".join(str(a) for row in rows for a in row)
        magma.append(f'Matrices["{name}"] := Matrix(Integers(), {n}, {n}, [{flat}]);')
        julia.append(f'MATRICES["{name}"] = matrix(ZZ, {n}, {n}, [{flat}])')
        expected = obj["expected"].get(name)
        if expected is None:
            continue
        for field, mag, jl in [("determinant", "ExpectedDet", "EXPECTED_DET"),
                               ("minimum", "ExpectedMin", "EXPECTED_MIN")]:
            magma.append(f'{mag}["{name}"] := {expected[field]};')
            julia.append(f'{jl}["{name}"] = {expected[field]}')
        shells = sorted((int(k), int(v)) for k, v in expected["theta_shells"].items())
        magma.append(f'ExpectedShells["{name}"] := [' + ", ".join(f"<{a},{b}>" for a, b in shells) + "];")
        julia.append(f'EXPECTED_SHELLS["{name}"] = Dict(' + ", ".join(f"{a} => {b}" for a, b in shells) + ")")
        if "smith_diagonal" in expected:
            diag = ", ".join(map(str, expected["smith_diagonal"]))
            magma.append(f'ExpectedSmith["{name}"] := [{diag}];')
            julia.append(f'EXPECTED_SMITH["{name}"] = [{diag}]')
    return {"lattices.m": "\n".join(magma) + "\n", "lattices.jl": "\n".join(julia) + "\n"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated inputs are stale.")
    args = parser.parse_args()
    for name, text in render().items():
        path = ROOT / "data" / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"STALE_ADAPTER_INPUT {path}")
        else:
            path.write_text(text, encoding="utf-8")
    print("ADAPTER_INPUTS_MATCH_JSON" if args.check else "ADAPTER_INPUTS_EXPORTED")


if __name__ == "__main__":
    main()
